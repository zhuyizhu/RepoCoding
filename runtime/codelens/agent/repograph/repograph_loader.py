from __future__ import annotations

import json
import logging
import os
import pickle
import threading
from collections import OrderedDict
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Optional, Set, Tuple

from agent.agents.models import GraphEdge
from agent.repograph.simple_graph import GraphData


logger = logging.getLogger(__name__)


@dataclass
class _RepographCacheEntry:
    graph: GraphData
    enriched_with_tags: bool


# GraphData is treated as read-only by the retrieval path. Keep only the most
# recent graph because a full benchmark traverses many base revisions and a
# large graph can occupy hundreds of MB after unpickling/conversion.
_REPOGRAPH_CACHE: "OrderedDict[Tuple[Any, ...], _RepographCacheEntry]" = OrderedDict()
_REPOGRAPH_CACHE_LOCK = threading.RLock()
_REPOGRAPH_CACHE_HITS = 0
_REPOGRAPH_CACHE_MISSES = 0


def _cache_max_entries() -> int:
    raw = (os.environ.get("JLOC_REPOGRAPH_CACHE_SIZE") or "1").strip()
    try:
        return max(0, int(raw))
    except ValueError:
        return 1


def _file_signature(path: Path) -> Optional[Tuple[int, int]]:
    try:
        stat = path.stat()
    except OSError:
        return None
    return stat.st_size, stat.st_mtime_ns


def _repograph_cache_key(repograph_dir: Path, prefer: str) -> Tuple[Any, ...]:
    try:
        canonical_dir = str(repograph_dir.resolve())
    except OSError:
        canonical_dir = str(repograph_dir.absolute())
    return (
        canonical_dir,
        prefer,
        _file_signature(repograph_dir / "graph.pkl"),
        _file_signature(repograph_dir / "tags.json"),
    )


def clear_repograph_cache() -> None:
    """Clear cached graphs, primarily for tests and long-lived worker control."""
    global _REPOGRAPH_CACHE_HITS, _REPOGRAPH_CACHE_MISSES
    with _REPOGRAPH_CACHE_LOCK:
        _REPOGRAPH_CACHE.clear()
        _REPOGRAPH_CACHE_HITS = 0
        _REPOGRAPH_CACHE_MISSES = 0


def repograph_cache_info() -> Dict[str, Any]:
    """Return lightweight cache diagnostics without exposing graph objects."""
    with _REPOGRAPH_CACHE_LOCK:
        return {
            "size": len(_REPOGRAPH_CACHE),
            "max_size": _cache_max_entries(),
            "hits": _REPOGRAPH_CACHE_HITS,
            "misses": _REPOGRAPH_CACHE_MISSES,
            "directories": [str(key[0]) for key in _REPOGRAPH_CACHE],
        }


def _format_line(line_value: Any) -> str:
    # graph/json may store:
    # - int
    # - [start, end]
    # - "?" or null
    if line_value is None:
        return "?"
    if isinstance(line_value, int):
        return str(line_value)
    if isinstance(line_value, (list, tuple)) and len(line_value) >= 1:
        if len(line_value) == 1 or line_value[0] == line_value[-1]:
            return str(line_value[0])
        return f"{line_value[0]}-{line_value[-1]}"
    return str(line_value)


def _node_payload_from_tags_obj(obj: Dict[str, Any]) -> Dict[str, Any]:
    # tags.json objects generated by `repograph/construct_graph.py`.
    # Some fields may be lists/empty; normalize to string-like for prompt.
    payload = dict(obj)
    payload["line_str"] = _format_line(obj.get("line"))
    # ensure comment is string-ish for prompt context
    payload["comment_str"] = obj.get("comment", "")
    if not isinstance(payload["comment_str"], str):
        payload["comment_str"] = str(payload["comment_str"])
    return payload


def _build_graph_from_tags(tags_json_path: Path) -> GraphData:
    nodes: Dict[str, Dict[str, Any]] = {}
    neighbors: Dict[str, Set[str]] = {}
    edges: list[GraphEdge] = []

    def add_undirected_edge(a: str, b: str) -> None:
        if a == b:
            # still keep the node in graph; but we skip self-loop for compactness
            neighbors.setdefault(a, set())
            return
        neighbors.setdefault(a, set()).add(b)
        neighbors.setdefault(b, set()).add(a)

    # We read line-by-line to keep memory usage reasonable.
    with open(tags_json_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            node_id = obj.get("name")
            if not node_id:
                continue

            nodes[node_id] = _node_payload_from_tags_obj(obj)
            neighbors.setdefault(node_id, set())

    # Reconstruct "contains" edges from class nodes' `info` (method list).
    for node_id, data in nodes.items():
        if data.get("category") != "class":
            continue
        info = data.get("info", "")
        if not info:
            continue
        if isinstance(info, str):
            method_names = [x.strip() for x in info.splitlines() if x.strip()]
        else:
            method_names = []
        for m in method_names:
            # methods can appear as nodes (kind=def) or may not; still connect.
            add_undirected_edge(node_id, m)
            edges.append(GraphEdge(src=node_id, dst=m, edge_type="contains", directed=True))

    return GraphData(nodes=nodes, neighbors=neighbors, source=f"tags.json:{tags_json_path}", edges=edges)


def _line_to_str(line_value: Any) -> str:
    if isinstance(line_value, (list, tuple)):
        return "-".join([str(x) for x in line_value])
    return str(line_value)


def _make_node_id(rel_fname: str, name: str, kind: str, category: str, line_value: Any) -> str:
    return f"{rel_fname}::{name}::{kind}::{category}::{_line_to_str(line_value)}"


def _enrich_nodes_with_tags(nodes: Dict[str, Dict[str, Any]], tags_json_path: Path) -> None:
    if not tags_json_path.exists():
        return
    with open(tags_json_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            node_id = _make_node_id(
                str(obj.get("rel_fname") or ""),
                str(obj.get("name") or ""),
                str(obj.get("kind") or ""),
                str(obj.get("category") or ""),
                obj.get("line"),
            )
            if node_id not in nodes:
                continue
            payload = nodes[node_id]
            for key in ("info", "comment", "annotations", "rel_fname", "fname", "kind", "category", "line"):
                val = obj.get(key)
                if val not in (None, "", [], {}):
                    payload[key] = val
            if not payload.get("comment_str"):
                payload["comment_str"] = payload.get("comment", "")
            if not payload.get("line_str") and payload.get("line") is not None:
                payload["line_str"] = _format_line(payload.get("line"))


def _load_repograph_uncached(
    repograph_dir_path: Path,
    *,
    prefer: str = "pkl",
    enrich_with_tags: bool = False,
) -> GraphData:
    pkl_path = repograph_dir_path / "graph.pkl"
    tags_path = repograph_dir_path / "tags.json"

    if prefer != "tags" and pkl_path.exists():
        try:
            with open(pkl_path, "rb") as f:
                # unpickling graph.pkl typically requires networkx; if missing, fallback.
                G = pickle.load(f)

            nodes: Dict[str, Dict[str, Any]] = {}
            neighbors: Dict[str, Set[str]] = {}
            typed_edges: list[GraphEdge] = []
            # networkx graph-like objects should support nodes(data=True)
            for node_id, data in G.nodes(data=True):
                payload = dict(data)
                payload["node_id"] = node_id
                if "line_str" not in payload:
                    payload["line_str"] = _format_line(payload.get("line") or payload.get("start_line"))
                if "comment_str" not in payload:
                    payload["comment_str"] = payload.get("comment", "")
                    if not isinstance(payload["comment_str"], str):
                        payload["comment_str"] = str(payload["comment_str"])
                nodes[str(node_id)] = payload
                neighbors.setdefault(str(node_id), set())

            # Build undirected adjacency while preserving typed directed edges for the upgraded CriticAgent.
            for u_raw, v_raw, edge_data in G.edges(data=True):
                u = str(u_raw)
                v = str(v_raw)
                neighbors.setdefault(u, set()).add(v)
                neighbors.setdefault(v, set()).add(u)
                typed_edges.append(
                    GraphEdge(
                        src=u,
                        dst=v,
                        edge_type=edge_data.get("edge_type", "unknown") if isinstance(edge_data, dict) else "unknown",
                        directed=True,
                        metadata=dict(edge_data) if isinstance(edge_data, dict) else {},
                    )
                )

            if enrich_with_tags:
                _enrich_nodes_with_tags(nodes, tags_path)
            return GraphData(nodes=nodes, neighbors=neighbors, source=f"graph.pkl:{pkl_path}", edges=typed_edges)
        except Exception:
            # Fallback to tags.json reconstruction.
            pass

    if not tags_path.exists():
        raise FileNotFoundError(
            f"repograph_dir must contain graph.pkl or tags.json. Got: {repograph_dir_path}"
        )

    return _build_graph_from_tags(tags_path)


def load_repograph(
    repograph_dir: str,
    *,
    prefer: str = "pkl",
    enrich_with_tags: bool = False,
) -> GraphData:
    """Load and process-cache a Repograph.

    Cache entries are keyed by canonical directory, load preference, and the
    size/mtime signatures of ``graph.pkl`` and ``tags.json``. Replacing either
    artifact therefore invalidates the entry automatically. If a cached graph
    is later requested with tag enrichment, it is enriched once in place; all
    retrieval callers treat GraphData as read-only, so this avoids a second
    full graph copy while retaining the richer metadata.

    Set ``JLOC_REPOGRAPH_CACHE_SIZE=0`` to disable caching. The default is 1 to
    bound memory across a multi-repository benchmark on an 8 GiB host.
    """
    global _REPOGRAPH_CACHE_HITS, _REPOGRAPH_CACHE_MISSES

    repograph_dir_path = Path(repograph_dir)
    normalized_prefer = (prefer or "pkl").strip().lower()
    max_entries = _cache_max_entries()
    if max_entries <= 0:
        return _load_repograph_uncached(
            repograph_dir_path,
            prefer=normalized_prefer,
            enrich_with_tags=enrich_with_tags,
        )

    cache_key = _repograph_cache_key(repograph_dir_path, normalized_prefer)
    tags_path = repograph_dir_path / "tags.json"
    with _REPOGRAPH_CACHE_LOCK:
        entry = _REPOGRAPH_CACHE.get(cache_key)
        if entry is not None:
            if enrich_with_tags and not entry.enriched_with_tags:
                _enrich_nodes_with_tags(entry.graph.nodes, tags_path)
                entry.enriched_with_tags = True
            _REPOGRAPH_CACHE.move_to_end(cache_key)
            _REPOGRAPH_CACHE_HITS += 1
            logger.info(
                "[RepoGraphCache] hit dir=%s nodes=%d enriched=%s",
                repograph_dir_path,
                len(entry.graph.nodes),
                entry.enriched_with_tags,
            )
            return entry.graph

    graph = _load_repograph_uncached(
        repograph_dir_path,
        prefer=normalized_prefer,
        enrich_with_tags=enrich_with_tags,
    )
    new_entry = _RepographCacheEntry(
        graph=graph,
        enriched_with_tags=bool(enrich_with_tags and tags_path.exists()),
    )
    with _REPOGRAPH_CACHE_LOCK:
        # Another worker may have populated the same key while this thread was
        # loading. Prefer that shared object so subsequent calls converge.
        existing = _REPOGRAPH_CACHE.get(cache_key)
        if existing is not None:
            if enrich_with_tags and not existing.enriched_with_tags:
                _enrich_nodes_with_tags(existing.graph.nodes, tags_path)
                existing.enriched_with_tags = True
            _REPOGRAPH_CACHE.move_to_end(cache_key)
            _REPOGRAPH_CACHE_HITS += 1
            return existing.graph

        _REPOGRAPH_CACHE[cache_key] = new_entry
        _REPOGRAPH_CACHE_MISSES += 1
        while len(_REPOGRAPH_CACHE) > max_entries:
            _REPOGRAPH_CACHE.popitem(last=False)
        logger.info(
            "[RepoGraphCache] miss/load dir=%s nodes=%d cache=%d/%d",
            repograph_dir_path,
            len(graph.nodes),
            len(_REPOGRAPH_CACHE),
            max_entries,
        )
    return graph


def normalize_node_text(node_id: str, node_data: Dict[str, Any]) -> str:
    # Used for prompt context; keep it deterministic and compact.
    rel_fname = node_data.get("rel_fname") or node_data.get("fname") or ""
    line_str = node_data.get("line_str") or _format_line(node_data.get("line"))
    category = node_data.get("category") or ""
    kind = node_data.get("kind") or ""
    info = node_data.get("info") or ""
    if isinstance(info, str):
        info = info.strip()
    else:
        info = str(info)
    comment_str = node_data.get("comment_str") or ""
    if isinstance(comment_str, str):
        comment_str = comment_str.strip()
    else:
        comment_str = str(comment_str)

    info_snip = info[:1200]
    comment_snip = comment_str[:300] if comment_str else ""
    if comment_snip:
        comment_part = f"Comment: {comment_snip}"
    else:
        comment_part = ""
    if comment_part:
        return (
            f"NodeId: {node_id}\n"
            f"File: {rel_fname}\n"
            f"Line: {line_str}\n"
            f"Category: {category} Kind: {kind}\n"
            f"{comment_part}\n"
            f"Info:\n{info_snip}"
        ).strip()
    return (
        f"NodeId: {node_id}\n"
        f"File: {rel_fname}\n"
        f"Line: {line_str}\n"
        f"Category: {category} Kind: {kind}\n"
        f"Info:\n{info_snip}"
    ).strip()
